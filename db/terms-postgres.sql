SET search_path = maker3d, pg_catalog;
CREATE TABLE IF NOT EXISTS terms_versions(version INTEGER PRIMARY KEY,title TEXT NOT NULL,body TEXT NOT NULL,published_at TEXT,published_by INTEGER REFERENCES users(id),created TEXT NOT NULL,updated TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS terms_acceptances(version INTEGER NOT NULL REFERENCES terms_versions(version),user_id INTEGER NOT NULL REFERENCES users(id),family_id INTEGER REFERENCES families(id),name TEXT NOT NULL,accepted_at TEXT NOT NULL,PRIMARY KEY(version,user_id));
CREATE INDEX IF NOT EXISTS maker_terms_family ON terms_acceptances(family_id,version);
ALTER TABLE terms_versions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS maker3d_backend ON terms_versions;
CREATE POLICY maker3d_backend ON terms_versions TO maker3d_app USING (true) WITH CHECK (true);
GRANT SELECT, INSERT, UPDATE, DELETE ON terms_versions TO maker3d_app;
REVOKE ALL ON terms_versions FROM PUBLIC, anon, authenticated;
ALTER TABLE terms_acceptances ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS maker3d_backend ON terms_acceptances;
CREATE POLICY maker3d_backend ON terms_acceptances TO maker3d_app USING (true) WITH CHECK (true);
GRANT SELECT, INSERT, UPDATE, DELETE ON terms_acceptances TO maker3d_app;
REVOKE ALL ON terms_acceptances FROM PUBLIC, anon, authenticated;
RESET search_path;
