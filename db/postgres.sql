CREATE SCHEMA maker3d;
SET search_path = maker3d, pg_catalog;
CREATE TABLE families(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,name TEXT NOT NULL,plan TEXT NOT NULL DEFAULT 'monthly',allowance INTEGER NOT NULL DEFAULT 720,created TEXT NOT NULL);
CREATE TABLE users(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,email TEXT UNIQUE NOT NULL,name TEXT NOT NULL,password TEXT NOT NULL,role TEXT NOT NULL,family_id INTEGER REFERENCES families(id));
CREATE TABLE sessions(token TEXT PRIMARY KEY,user_id INTEGER REFERENCES users(id),expires BIGINT NOT NULL);
CREATE TABLE invites(token TEXT PRIMARY KEY,family_id INTEGER NOT NULL REFERENCES families(id),role TEXT NOT NULL,expires BIGINT NOT NULL);
CREATE TABLE participants(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,family_id INTEGER NOT NULL REFERENCES families(id),name TEXT NOT NULL);
CREATE TABLE projects(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,family_id INTEGER NOT NULL REFERENCES families(id),name TEXT NOT NULL,description TEXT NOT NULL,participant TEXT NOT NULL,kind TEXT NOT NULL,size TEXT NOT NULL,color TEXT NOT NULL,quantity INTEGER NOT NULL,status TEXT NOT NULL DEFAULT 'draft',created TEXT NOT NULL,updated TEXT NOT NULL,minutes INTEGER NOT NULL DEFAULT 0,grams DOUBLE PRECISION NOT NULL DEFAULT 0,material TEXT NOT NULL DEFAULT '',material_rate INTEGER NOT NULL DEFAULT 0,extra_rate INTEGER NOT NULL DEFAULT 600,included INTEGER NOT NULL DEFAULT 0,period TEXT,approved_at TEXT,quote_note TEXT NOT NULL DEFAULT '',actual_minutes INTEGER,actual_grams DOUBLE PRECISION,used INTEGER NOT NULL DEFAULT 0,charge INTEGER NOT NULL DEFAULT 0,paid INTEGER NOT NULL DEFAULT 0);
CREATE TABLE events(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,project_id INTEGER NOT NULL REFERENCES projects(id),text TEXT NOT NULL,created TEXT NOT NULL);
CREATE TABLE messages(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,project_id INTEGER NOT NULL REFERENCES projects(id),user_id INTEGER NOT NULL REFERENCES users(id),body TEXT NOT NULL,created TEXT NOT NULL);
CREATE TABLE files(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,project_id INTEGER NOT NULL REFERENCES projects(id),name TEXT NOT NULL,path TEXT NOT NULL,size INTEGER NOT NULL);
CREATE TABLE settings(id INTEGER PRIMARY KEY CHECK(id=1),value TEXT NOT NULL);
CREATE TABLE payments(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,family_id INTEGER NOT NULL REFERENCES families(id),description TEXT NOT NULL,cents INTEGER NOT NULL,created TEXT NOT NULL);

ALTER TABLE users ADD CONSTRAINT maker_role CHECK(role IN ('admin','guardian','learner'));
ALTER TABLE users ADD CONSTRAINT maker_family_role CHECK((role='admin' AND family_id IS NULL) OR (role IN ('guardian','learner') AND family_id IS NOT NULL));
ALTER TABLE projects ADD CONSTRAINT maker_status CHECK(status IN ('draft','review','question','approval','queued','printing','ready','completed','cancelled','failed'));
ALTER TABLE projects ADD CONSTRAINT maker_quantity CHECK(quantity BETWEEN 1 AND 50);
ALTER TABLE projects ADD CONSTRAINT maker_nonnegative CHECK(minutes>=0 AND grams>=0 AND included>=0 AND used>=0 AND charge>=0);
ALTER TABLE invites ADD CONSTRAINT maker_invite_role CHECK(role IN ('guardian','learner'));
CREATE INDEX maker_projects_family_period ON projects(family_id,period);
CREATE INDEX maker_projects_queue ON projects(approved_at,id) WHERE status='queued';
CREATE UNIQUE INDEX maker_one_print ON projects((status)) WHERE status='printing';
CREATE INDEX maker_users_family ON users(family_id);
CREATE INDEX maker_sessions_user ON sessions(user_id);
CREATE INDEX maker_sessions_expires ON sessions(expires);
CREATE INDEX maker_invites_family ON invites(family_id);
CREATE INDEX maker_participants_family ON participants(family_id);
CREATE INDEX maker_events_project ON events(project_id,id);
CREATE INDEX maker_messages_project ON messages(project_id,id);
CREATE INDEX maker_messages_user ON messages(user_id);
CREATE INDEX maker_files_project ON files(project_id);
CREATE INDEX maker_payments_family ON payments(family_id,id);

